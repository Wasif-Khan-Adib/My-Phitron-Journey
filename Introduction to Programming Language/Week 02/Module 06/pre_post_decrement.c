#include<stdio.h>
int main()
{
    int x=10;
    --x; //এখানে ভ্যালু ১ কমে হইছে, ৯
    printf("%d\n",x--); // এখানে ৯ প্রিন্ট হবে কারণ পোস্ট ডিক্রিমেন্টে আগে 
    //কাজ হয় পরে ডিক্রিমেন্ট হয়। 
    printf("%d",x); // এখানে ভ্যালু আসবে ৮ কারণ, কাজ শেষ, এখন পোস্ট
    // ডিক্রিমেন্ট হয়েছে। 
    return 0;
}